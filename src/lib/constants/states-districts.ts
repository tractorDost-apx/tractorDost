const stateKey = (s: string) => s.replace(/&/g, ' and ').toLowerCase().replace(/[^a-z0-9]/g, '');

const STATE_LOOKUP = new Map<string, string>([
  ...INDIAN_STATES.map((s): [string, string] => [stateKey(s), s]),
  ['orissa', 'Odisha'],
  ['pondicherry', 'Puducherry'],
  ['newdelhi', 'Delhi'],
  ['nctofdelhi', 'Delhi'],
  ['uttaranchal', 'Uttarakhand'],
]);

export function resolveState(input: string): string | undefined {
  if (!input) return undefined;
  return STATE_LOOKUP.get(stateKey(input));
}

export function getDistrictsByState(state: string): string[] {
  const resolved = resolveState(state);
  if (!resolved) return [];
  return STATE_DISTRICTS[resolved] || [];
}

